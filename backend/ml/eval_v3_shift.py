"""World-v3 distribution shift, measured BEFORE retraining (SYNTHETIC VALIDATION).

    cd backend
    <venv>/python ml/eval_v3_shift.py        # ~1 min; writes models/validation_v3_shift.json

Scores the 30 TEST worlds (indices 120-149, seed 20261006) twice — as generated by datagen v2.1 (no everyday
economy) and by datagen v3.0 (same worlds plus the everyday-economy layer) — with the artefacts committed at the
time it is run, through the SERVING path (vigil.intel.models numpy ports + stored isotonic knots). It also
compares early warning v2.0 (legacy signals, reproduced below for the comparison only) with v3.0 on both.
Run once against the v2.1 artefacts before `ml/train_all.py` replaced them; the committed JSON is that run.
No model is fitted here.
"""

from __future__ import annotations

import json
import sys
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

BACKEND = Path(__file__).resolve().parents[1]
if str(BACKEND) not in sys.path:
    sys.path.insert(0, str(BACKEND))

import numpy as np  # noqa: E402

from ml import datagen, metrics as M  # noqa: E402
from ml.eval_roles_consensus import committed_scores  # noqa: E402
from ml.train_all import DETECTORS, LABEL, MODELS, N_TEST, N_TRAIN, N_VAL, SEED, log, process  # noqa: E402
from vigil.intel import early_warning as EW  # noqa: E402
from vigil.intel.models import STORE  # noqa: E402

OUT = MODELS / "validation_v3_shift.json"


def legacy_ew_raw(f: dict[str, float], stats: dict[str, float]) -> tuple[float, list[str]]:
    """early-warning-v2.0 signals (population-relative velocity, any 3 recipients) — comparison only."""
    signals: list[str] = []
    score = 0.0
    age_ref = min(stats["age_p30"], EW.NEW_ACCOUNT_CAP_DAYS)
    if f["account_age_days"] < age_ref and f["transaction_count"] > 0:
        score += 0.25 * (1.0 - f["account_age_days"] / max(age_ref, 1.0))
        signals.append("New Account")
    if f["device_cluster_size"] >= 3:
        score += 0.20 * min(f["device_cluster_size"] / 10.0, 1.0)
        signals.append("Shared Device")
    if f["retention_ratio"] < 0.20 and f["total_in_amount"] >= 5_000:
        score += 0.20 * (1.0 - f["retention_ratio"] / 0.20)
        signals.append("Pass-Through")
    z = (f["transaction_count"] - stats["mean_tx"]) / stats["std_tx"]
    if z > 1.5:
        score += min(z * 0.08, 0.25)
        signals.append("High Velocity")
    if f["out_degree"] >= 3:
        score += 0.15 * min(f["out_degree"] / 5.0, 1.0)
        signals.append("High Fan-Out")
    if f["unique_channels"] >= 3:
        score += 0.15
        signals.append("Multi-Channel")
    if len(signals) < EW.MIN_SIGNALS:
        score *= 0.2
    return round(score, 4), signals


def legacy_ew(tables: list[dict[str, Any]]) -> tuple[np.ndarray, np.ndarray]:
    scores, flags = [], []
    for t in tables:
        feats = t["feats"]
        _, stats = EW.evaluate_population(feats)          # same age / velocity statistics
        raws = [legacy_ew_raw(feats[a], stats) for a in t["ids"]]
        top = sorted((r[0] for r in raws), reverse=True)
        cut = max(EW.MIN_SCORE, top[max(1, int(len(top) * EW.EARLY_TOP_PCT)) - 1])
        scores += [r[0] for r in raws]
        flags += [len(r[1]) >= EW.MIN_SIGNALS and r[0] >= cut for r in raws]
    return np.array(scores), np.array(flags, dtype=bool)


def summary(s: dict[str, Any], mask: np.ndarray | None = None) -> dict[str, Any]:
    y, kind = s["y"], np.array(s["kind"])
    m = np.ones(len(y), dtype=bool) if mask is None else mask
    fam = [f for f, keep in zip(s["fam"], m) if keep]
    out: dict[str, Any] = {"accounts": int(m.sum()), "mules": int(y[m].sum())}
    for d in DETECTORS + ("early_warning_v2_0",):
        score, flag = s[d]
        r = M.binary(y[m], score[m], flag[m])
        neg = (y == 0) & m
        out[d] = {k: r[k] for k in ("precision", "recall", "f1", "pr_auc", "confusion")}
        out[d]["per_attack_recall"] = {f: v["recall"] for f, v in M.per_attack(y[m], flag[m], fam).items()}
        out[d]["false_positives_by_persona"] = {k: int((flag & neg & (kind == k)).sum()) for k in sorted(set(kind[neg]))}
    return out


def main() -> None:
    t0 = time.perf_counter()
    idx = range(N_TRAIN + N_VAL, N_TRAIN + N_VAL + N_TEST)
    STORE.load()
    result: dict[str, Any] = {
        "label": LABEL, "data": "SYNTHETIC", "command": "python ml/eval_v3_shift.py",
        "evaluated_at": datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z"),
        "artefacts": {"random_forest": STORE.rf_meta.get("version"), "gnn": STORE.gnn_meta.get("version"),
                      "trained_at": STORE.rf_meta.get("trained_at")},
        "early_warning": {"v2_0": "legacy signals (population-relative velocity, any 3 recipients)",
                          "v3_0": EW.EW_VERSION},
        "test_worlds": f"indices {idx.start}..{idx.stop - 1}, seed {SEED}",
    }
    for gen, everyday in (("datagen_v2_1", False), ("datagen_v3_0", True)):
        tables = [process(datagen.make_world(i, SEED, everyday=everyday)) for i in idx]
        s = committed_scores(tables)
        s["early_warning_v2_0"] = legacy_ew(tables)
        dense = np.concatenate([np.full(len(t["ids"]), bool(t["world"].everyday)) for t in tables])
        result[gen] = {"all": summary(s), "everyday_worlds": summary(s, dense) if dense.any() else None,
                       "sparse_worlds": summary(s, ~dense) if (~dense).any() else None,
                       "worlds_with_everyday_economy": int(sum(bool(t["world"].everyday) for t in tables))}
        log(f"{gen}: scored [{time.perf_counter() - t0:.1f}s]")
    OUT.write_text(json.dumps(result, indent=1, default=float), encoding="utf-8")
    print()
    print(LABEL)
    for gen in ("datagen_v2_1", "datagen_v3_0"):
        for part in ("all", "everyday_worlds", "sparse_worlds"):
            r = result[gen][part]
            if not r:
                continue
            row = "  ".join(f"{d[:6]} P={r[d]['precision']:.2f} R={r[d]['recall']:.2f}" for d in DETECTORS + ("early_warning_v2_0",))
            print(f"{gen:13s} {part:15s} n={r['accounts']:5d} mules={r['mules']:3d}  {row}")
    log(f"written {OUT} [{time.perf_counter() - t0:.1f}s]")


if __name__ == "__main__":
    main()
